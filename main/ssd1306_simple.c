#include "driver/i2c.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"
#include <string.h>
#include "ssd1306_simple.h"

#define TAG "SSD1306"
#define SSD1306_ADDR 0x3C
#define I2C_PORT I2C_NUM_0

// 5x7 ASCII font (A–Z and space)
static const uint8_t font5x7[][5] = {
    {0x00,0x00,0x00,0x00,0x00}, // space
    {0x7E,0x11,0x11,0x11,0x7E}, // A
    {0x7F,0x49,0x49,0x49,0x36}, // B
    {0x3E,0x41,0x41,0x41,0x22}, // C
    {0x7F,0x41,0x41,0x22,0x1C}, // D
    {0x7F,0x49,0x49,0x49,0x41}, // E
    {0x7F,0x09,0x09,0x09,0x01}, // F
    {0x3E,0x41,0x49,0x49,0x7A}, // G
    {0x7F,0x08,0x08,0x08,0x7F}, // H
    {0x00,0x41,0x7F,0x41,0x00}, // I
    {0x20,0x40,0x41,0x3F,0x01}, // J
    {0x7F,0x08,0x14,0x22,0x41}, // K
    {0x7F,0x40,0x40,0x40,0x40}, // L
    {0x7F,0x02,0x0C,0x02,0x7F}, // M
    {0x7F,0x04,0x08,0x10,0x7F}, // N
    {0x3E,0x41,0x41,0x41,0x3E}, // O
    {0x7F,0x09,0x09,0x09,0x06}, // P
    {0x3E,0x41,0x51,0x21,0x5E}, // Q
    {0x7F,0x09,0x19,0x29,0x46}, // R
    {0x26,0x49,0x49,0x49,0x32}, // S
    {0x01,0x01,0x7F,0x01,0x01}, // T
    {0x3F,0x40,0x40,0x40,0x3F}, // U
    {0x1F,0x20,0x40,0x20,0x1F}, // V
    {0x7F,0x20,0x18,0x20,0x7F}, // W
    {0x63,0x14,0x08,0x14,0x63}, // X
    {0x07,0x08,0x70,0x08,0x07}, // Y
    {0x61,0x51,0x49,0x45,0x43}  // Z
};

// Send one command byte
static void ssd1306_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_write_to_device(I2C_PORT, SSD1306_ADDR, buf, 2, 100 / portTICK_PERIOD_MS);
}

// Initialize the display
void ssd1306_init(void) {
    uint8_t cmds[] = {
        0xAE,0xD5,0x80,0xA8,0x3F,0xD3,0x00,0x40,
        0x8D,0x14,0x20,0x00,0xA1,0xC8,0xDA,0x12,
        0x81,0x7F,0xA4,0xA6,0xAF
    };
    for (int i = 0; i < sizeof(cmds); i++)
        ssd1306_cmd(cmds[i]);
    ESP_LOGI(TAG, "SSD1306 initialized");
}

// Fill entire screen (color 0=off, 1=on)
void ssd1306_fill(uint8_t color) {
    for (uint8_t page = 0; page < 8; page++) {
        uint8_t set[] = {0x00, (uint8_t)(0xB0 + page), 0x00, 0x10};
        i2c_master_write_to_device(I2C_PORT, SSD1306_ADDR, set, sizeof(set), 10 / portTICK_PERIOD_MS);
        uint8_t data[129];
        data[0] = 0x40;
        memset(&data[1], color ? 0xFF : 0x00, 128);
        i2c_master_write_to_device(I2C_PORT, SSD1306_ADDR, data, sizeof(data), 10 / portTICK_PERIOD_MS);
    }
}

// Draw text starting at (x, page)
void ssd1306_draw_text(uint8_t x, uint8_t page, const char *text) {
    while (*text) {
        char c = *text++;
        if (c >= 'A' && c <= 'Z') {
            const uint8_t *glyph = font5x7[c - 'A' + 1]; // +1 to skip space
            uint8_t data[6];
            data[0] = 0x40;
            memcpy(&data[1], glyph, 5);
            data[6] = 0x00;

            uint8_t set[] = {0x00, (uint8_t)(0xB0 + page),
                             (uint8_t)(x & 0x0F),
                             (uint8_t)(0x10 | (x >> 4))};
            i2c_master_write_to_device(I2C_PORT, SSD1306_ADDR, set, sizeof(set), 10 / portTICK_PERIOD_MS);
            i2c_master_write_to_device(I2C_PORT, SSD1306_ADDR, data, sizeof(data), 10 / portTICK_PERIOD_MS);
            x += 6;
        } else {
            x += 6; // skip unknown char space
        }
    }
}